import sys
from playwright.sync_api import sync_playwright
port = sys.argv[1]
url = f"http://localhost:{port}/_parts/gh4/wtest2.html"
S = "_parts/gh4/shots/"
def W(pg, name): return pg.locator(f".widget[data-widget={name}]")
EM = """([v, i]) => { const V = window.__views[v]; V.c.scrollIntoView({block: "center", behavior: "instant"}); const G = V.edgeGeom(i), r = V.c.getBoundingClientRect(); return [r.left + G.mx, r.top + G.my]; }"""
NM = """([v, i]) => { const V = window.__views[v]; V.c.scrollIntoView({block: "center", behavior: "instant"}); const n = V.nodes[i], r = V.c.getBoundingClientRect(); return [r.left + n.x * V.w, r.top + n.y * V.h]; }"""
def ce(pg, v, i): x, y = pg.evaluate(EM, [v, i]); pg.mouse.click(x, y)
def cn(pg, v, i): x, y = pg.evaluate(NM, [v, i]); pg.mouse.click(x, y)
def txt(l): return l.inner_text().replace("\n", " | ")
def bars(w): return " ".join(w.locator("div[style*='grid-template-columns:2.2em']").all_inner_texts()).replace("\n", " ")
with sync_playwright() as p:
    b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1000, "height": 900})
    errs = []
    pg.on("console", lambda m: errs.append(m.type + ": " + m.text) if m.type in ("error", "warning") else None)
    pg.on("pageerror", lambda e: errs.append("PAGEERROR " + str(e)))
    pg.goto(url); pg.wait_for_load_state("networkidle"); pg.wait_for_timeout(800)
    print("views:", pg.evaluate("window.__views.length"))
    # ---------- random-surfer (view 0)
    r = W(pg, "random-surfer")
    r.scroll_into_view_if_needed()
    for k in range(5): r.get_by_role("button", name="Lépés", exact=True).click(); pg.wait_for_timeout(300)
    print("rs after 5:", txt(r.locator(".readout")))
    for k in range(20): r.locator("button", has_text="+1000").click()
    print("rs arviz 20k:", bars(r)); print("  ", txt(r.locator(".readout")))
    r.screenshot(path=S + "w2-surfer-arviz.png")
    r.locator("input[type=checkbox]").check()
    for k in range(20): r.locator("button", has_text="+1000").click()
    print("rs arviz W 20k:", bars(r)); print("  ", txt(r.locator(".readout")))
    r.screenshot(path=S + "w2-surfer-arviz-w.png")
    r.locator("button", has_text="barátsággráf").click()
    for k in range(20): r.locator("button", has_text="+1000").click()
    print("rs barat:", bars(r)); print("  ", txt(r.locator(".readout")))
    r.locator("button", has_text="csillag").click()
    for k in range(10): r.locator("button", has_text="+1000").click()
    print("rs star:", bars(r)); print("  ", txt(r.locator(".readout")))
    r.screenshot(path=S + "w2-surfer-star.png")
    r.locator("button", has_text="lapok").click()
    for k in range(3): r.locator("button", has_text="+1000").click()
    print("rs papers:", bars(r)); print("  ", txt(r.locator(".readout")))
    print("papers outdeg:", pg.evaluate("window.__views[0].edges.map(e => window.__views[0].nodes[e.a].label + '>' + window.__views[0].nodes[e.b].label).join(' ')"))
    r.screenshot(path=S + "w2-surfer-papers.png")
    r.locator("button", has_text="Árvízhét").click()
    r.locator("button", has_text="Indít").click(); pg.wait_for_timeout(1600)
    print("rs playing:", txt(r.locator(".readout")).split("|")[0], r.locator("button.primary").inner_text())
    r.screenshot(path=S + "w2-surfer-play.png")
    # görgetés el -> megáll
    W(pg, "spectral-cut").scroll_into_view_if_needed(); pg.wait_for_timeout(500)
    print("after scroll away:", r.locator("button.primary").inner_text())
    # ---------- laplacian (view 1)
    l = W(pg, "laplacian-smooth")
    l.scroll_into_view_if_needed()
    print("lap p3 default:", txt(l.locator(".readout").first))
    def setsl(vals):
        for i, v in enumerate(vals):
            pg.evaluate("([i, v]) => { const s = document.querySelectorAll('.widget[data-widget=laplacian-smooth] input[type=range]')[i]; s.value = v; s.dispatchEvent(new Event('input')); }", [i, v])
    setsl([1, 3, 1]); print("lap (1,3,1):", txt(l.locator(".readout").first))
    l.get_by_role("button", name="konstans", exact=True).click(); print("lap const:", txt(l.locator(".readout").first))
    l.locator("button", has_text="Fiedler").click(); print("lap fiedler:", txt(l.locator(".readout").first))
    print("spec p3:", txt(l.locator(".readout").nth(1)))
    setsl([1, 2, 3]); ce(pg, 1, 0); print("lap edge click:", txt(l.locator(".readout").first))
    l.screenshot(path=S + "w2-lap-p3.png")
    l.locator("button", has_text="két háromszög").click()
    print("spec tt:", txt(l.locator(".readout").nth(1)))
    l.locator("label", has_text="híd").locator("input").check()
    print("spec tt nobridge:", txt(l.locator(".readout").nth(1)), "|", txt(l.locator(".readout").first))
    l.screenshot(path=S + "w2-lap-tt-nobridge.png")
    l.locator("label", has_text="híd").locator("input").uncheck()
    l.locator("button", has_text="ugráló").click()
    l.locator("label", has_text="szerkesztés").locator("input").check()
    cn(pg, 1, 0); cn(pg, 1, 4)
    print("spec tt +edge 1-5:", txt(l.locator(".readout").nth(1)))
    l.locator("button", has_text="Árvízhét").click(); l.locator("button", has_text="Fiedler").click()
    print("lap arviz fiedler:", txt(l.locator(".readout").first)); print("spec arviz:", txt(l.locator(".readout").nth(1)))
    l.screenshot(path=S + "w2-lap-arviz.png")
    # ---------- spectral (view 2)
    c = W(pg, "spectral-cut")
    print("sc tt:", txt(c.locator(".readout")))
    print("sc tt vec:", pg.evaluate("window.__views[2].nodes.map(n => n.sub).join(' ')"))
    c.screenshot(path=S + "w2-cut-tt.png")
    c.locator("button", has_text="Előjelcsere").click(); print("sc flip:", txt(c.locator(".readout")))
    c.locator("button", has_text="Árvízhét").click(); print("sc arviz:", txt(c.locator(".readout")))
    c.screenshot(path=S + "w2-cut-arviz.png")
    c.locator("button", has_text="mediánnál").click(); print("sc arviz median:", txt(c.locator(".readout")))
    c.locator("button", has_text="előjelnél").click()
    c.locator("button", has_text="karateklub").click()
    c.locator("label", has_text="valódi").locator("input").check()
    print("sc karate:", txt(c.locator(".readout")))
    c.screenshot(path=S + "w2-cut-karate.png")
    c.locator("button", has_text="mediánnál").click(); print("sc karate median:", txt(c.locator(".readout")))
    c.locator("button", has_text="előjelnél").click()
    # szerkesztés: két háromszög, a híd (él 3) törlése élre kattintva
    c.locator("button", has_text="két háromszög").click()
    ce(pg, 2, 3); print("sc tt no bridge:", txt(c.locator(".readout")))
    c.screenshot(path=S + "w2-cut-disc.png")
    c.locator("button", has_text="üres").click(); print("sc empty:", txt(c.locator(".readout")))
    box = pg.evaluate("(() => { const r = window.__views[2].c.getBoundingClientRect(); return [r.left, r.top, r.width, r.height]; })()")
    for fx, fy in [(.2, .3), (.5, .3), (.8, .5)]: pg.mouse.click(box[0] + fx * box[2], box[1] + fy * box[3])
    cn(pg, 2, 0); cn(pg, 2, 1); cn(pg, 2, 1); cn(pg, 2, 2)
    print("sc built:", txt(c.locator(".readout")))
    pg.screenshot(path=S + "w2-full-light.png", full_page=True)
    # sötét
    pg.evaluate("document.documentElement.setAttribute('data-theme','dark')"); pg.wait_for_timeout(300)
    c.locator("button", has_text="karateklub").click(); c.locator("label", has_text="valódi").locator("input").check()
    r.screenshot(path=S + "w2-surfer-dark.png"); l.screenshot(path=S + "w2-lap-dark.png"); c.screenshot(path=S + "w2-cut-dark.png")
    pg.evaluate("document.documentElement.setAttribute('data-theme','light')")
    # mobil
    pg.set_viewport_size({"width": 390, "height": 850}); pg.reload(); pg.wait_for_load_state("networkidle"); pg.wait_for_timeout(800)
    r = W(pg, "random-surfer"); l = W(pg, "laplacian-smooth"); c = W(pg, "spectral-cut")
    for k in range(5): r.locator("button", has_text="+1000").click()
    r.screenshot(path=S + "w2-surfer-mobile.png")
    l.locator("button", has_text="két háromszög").click(); l.screenshot(path=S + "w2-lap-mobile.png")
    c.locator("button", has_text="Árvízhét").click(); c.screenshot(path=S + "w2-cut-mobile.png")
    print("overflow:", pg.evaluate("document.documentElement.scrollWidth"))
    print("errors:", errs)
    b.close()
