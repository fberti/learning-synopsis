                rm.screenshot(path=f"{OUT}/int-rm-L0.png")
                setr(rm.locator("input[type=range]").nth(0), 0); setr(rm.locator("input[type=range]").nth(1), 10); pg.wait_for_timeout(50); res["rm-0-10"] = stats(rm)
                rm.screenshot(path=f"{OUT}/int-rm-T0.png")
                setr(rm.locator("input[type=range]").nth(1), 0); pg.wait_for_timeout(50); res["rm-0-0"] = stats(rm)
