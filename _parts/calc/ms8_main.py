def welch(m1,s1,n1,m2,s2,n2):
    v1,v2=s1**2/n1,s2**2/n2; se=np.sqrt(v1+v2); t=(m1-m2)/se; df=(v1+v2)**2/(v1**2/(n1-1)+v2**2/(n2-1))
    sp2=((n1-1)*s1**2+(n2-1)*s2**2)/(n1+n2-2); sep=np.sqrt(sp2*(1/n1+1/n2)); tp=(m1-m2)/sep
    return dict(se=se,t=t,df=df,p=2*st.t.sf(abs(t),df), p_cons=2*st.t.sf(abs(t),min(n1,n2)-1), sep=sep,tp=tp,pp=2*st.t.sf(abs(tp),n1+n2-2))
