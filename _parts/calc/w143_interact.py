from playwright.sync_api import sync_playwright
URL = "http://localhost:8831/_parts/ch14/wtest3.html"
errs = []
with sync_playwright() as p:
    b = p.chromium.launch()
    for W in (1280, 380):
        pg = b.new_page(viewport={"width": W, "height": 800}, has_touch=True)
        pg.on("console", lambda m: m.type in ("error", "warning") and errs.append(m.text))
        pg.on("pageerror", lambda e: errs.append(str(e)))
        pg.goto(URL); pg.wait_for_timeout(1200)
        d2 = pg.locator('[data-widget="diffusion-2d"]')
        # előre fül: kattintás egy pontra (a kijelölt pont váltása)
        cv = d2.locator("canvas").nth(1); cv.scroll_into_view_if_needed()
        bb = cv.bounding_box()
        before = d2.locator(".readout").inner_text()
        d2.locator("input[type=range]").first.fill("0"); 
        cv.click(position={"x": bb["width"] / 2, "y": bb["height"] * 0.2})
        d2.get_by_role("button", name="Új zaj").click()
        d2.get_by_role("button", name="Visszafelé: mintavétel").click()
        pg.wait_for_timeout(700)
        k1 = int(d2.locator("input[type=range]").nth(2).input_value())
        pg.wait_for_timeout(700)
        k2 = int(d2.locator("input[type=range]").nth(2).input_value())
        print(W, "anim fut:", k1, "->", k2)
        # elgörgetjük: álljon le
        pg.evaluate("window.scrollTo(0, 2600)"); pg.wait_for_timeout(400)
        k3 = int(d2.locator("input[type=range]").nth(2).input_value()); pg.wait_for_timeout(800)
        k4 = int(d2.locator("input[type=range]").nth(2).input_value())
        print(W, "nem látszik:", k3, "->", k4)
        d2.scroll_into_view_if_needed(); pg.wait_for_timeout(600)
        k5 = int(d2.locator("input[type=range]").nth(2).input_value()); print(W, "újra látszik:", k5)
        d2.get_by_role("button", name="⏸ Szünet").click(); pg.wait_for_timeout(300)
        k6 = int(d2.locator("input[type=range]").nth(2).input_value()); pg.wait_for_timeout(500)
        print(W, "szünet:", k6, int(d2.locator("input[type=range]").nth(2).input_value()))
        # 1000 lépés + lejátszás a végéig
        d2.get_by_role("button", name="1000", exact=True).click()
        d2.get_by_role("button", name="▶ Lejátszás").click(); pg.wait_for_timeout(6000)
        print(W, "1000 lépés vége:", d2.locator(".readout").inner_text().replace("\n", " "), "| stat:", d2.locator(".stat .v").first.inner_text())
        # kattintás egy mintára (érintés)
        cv = d2.locator("canvas").nth(1); bb = cv.bounding_box()
        o = pg.evaluate("document.querySelector('[data-widget=\"diffusion-2d\"]').__w3.final.slice(0,40)")
        print(W, "note előtte:", d2.locator("p.muted").last.inner_text()[:80])
        # első minta 5-ös indexű pozíciója a zoom vásznon: az eqView-ból számoljuk, inkább csak tap középre
        cv.tap(position={"x": bb["width"] * 0.5, "y": bb["height"] * 0.5})
        print(W, "note utána:", d2.locator("p.muted").last.inner_text()[:80])
        cf = pg.locator('[data-widget="cfg-2d"]')
        cf.locator("input[type=range]").fill("5"); cf.get_by_role("button", name="Új mag").click(); cf.get_by_role("button", name="B osztály").click()
        print(W, "cfg:", [x.inner_text() for x in cf.locator(".stat .v").all()])
        dd = pg.locator('[data-widget="diffusion-digits"]')
        dd.get_by_role("button", name="7", exact=True).click(); dd.locator("input[type=range]").fill("999")
        print(W, "dd:", dd.locator(".readout").inner_text().replace("\n", " | "))
        pg.close()
    b.close()
print("ERRS", errs)
