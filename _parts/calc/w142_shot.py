import sys, os
from playwright.sync_api import sync_playwright
URL = "http://localhost:8821/_parts/ch14/wtest2.html"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ch14", "shots2")
os.makedirs(OUT, exist_ok=True)
errs = []
with sync_playwright() as p:
    b = p.chromium.launch()
    for theme in (["light", "dark"] if len(sys.argv) < 2 else [sys.argv[1]]):
        for wd in ([1280, 380] if len(sys.argv) < 3 else [int(sys.argv[2])]):
            pg = b.new_page(viewport={"width": wd, "height": 900})
            pg.on("console", lambda m: m.type in ("error", "warning") and errs.append(f"{theme}{wd}: {m.text}"))
            pg.on("pageerror", lambda e: errs.append(f"{theme}{wd} PAGEERR: {e}"))
            pg.goto(URL); pg.wait_for_timeout(1200)
            if theme == "dark":
                pg.evaluate("document.documentElement.setAttribute('data-theme','dark')"); pg.wait_for_timeout(300)
            # latent-map: random, drag
            lm = pg.locator("#w-lm")
            lm.get_by_role("button", name="Véletlen kód 𝒩(0, I)-ből").click()
            cv = lm.locator("canvas").first; bb = cv.bounding_box()
            pg.mouse.move(bb["x"] + bb["width"] * 0.3, bb["y"] + bb["height"] * 0.6); pg.mouse.down()
            pg.mouse.move(bb["x"] + bb["width"] * 0.45, bb["y"] + bb["height"] * 0.5, steps=5); pg.mouse.up()
            lm.screenshot(path=f"{OUT}/lm_ae_{theme}_{wd}.png")
            lm.get_by_role("button", name="VAE").click()
            lm.get_by_role("button", name="Véletlen kód 𝒩(0, I)-ből").click()
            lm.screenshot(path=f"{OUT}/lm_vae_{theme}_{wd}.png")
            # gan-1d: run some steps
            g1 = pg.locator("#w-g1")
            g1.scroll_into_view_if_needed()
            g1.get_by_role("button", name="▶ Indítás").click()
            pg.wait_for_timeout(2500)
            g1.get_by_role("button", name="⏸ Szünet").click()
            g1.screenshot(path=f"{OUT}/g1_{theme}_{wd}.png")
            print("G1-one", g1.locator(".readout").inner_text().replace("\n", " | "))
            g1.get_by_role("button", name="két csúcs").click()
            g1.get_by_role("button", name="Új mag").click()
            g1.get_by_role("button", name="▶ Indítás").click()
            pg.wait_for_timeout(2000)
            g1.get_by_role("button", name="⏸ Szünet").click()
            g1.screenshot(path=f"{OUT}/g1two_{theme}_{wd}.png")
            print("G1-two-seed2", g1.locator(".readout").inner_text().replace("\n", " | "))
            g1.get_by_role("button", name="egy csúcs").click()
            g1.get_by_role("button", name="minimax: ln(1 − D(G(z)))").click()
            g1.get_by_text("a hamisító messziről indul").click()
            g1.get_by_role("button", name="▶ Indítás").click()
            pg.wait_for_timeout(1500)
            g1.get_by_role("button", name="⏸ Szünet").click()
            g1.screenshot(path=f"{OUT}/g1mm_{theme}_{wd}.png")
            print("G1-mm-far-seed2", g1.locator(".readout").inner_text().replace("\n", " | "))
            ge = pg.locator("#w-ge"); ge.scroll_into_view_if_needed(); ge.locator("input[type=range]").fill("2")
            ge.screenshot(path=f"{OUT}/ge_{theme}_{wd}.png")
            gc = pg.locator("#w-gc"); gc.scroll_into_view_if_needed()
            gc.get_by_role("button", name="másoló").click()
            c2 = gc.locator("canvas").first; bb = c2.bounding_box()
            pg.mouse.click(bb["x"] + bb["width"] * 0.3, bb["y"] + bb["height"] * 0.3)
            gc.screenshot(path=f"{OUT}/gc_{theme}_{wd}.png")
            gc.get_by_role("button", name="Melyik az igazi?").click()
            gc.locator("canvas").nth(3).click()
            gc.screenshot(path=f"{OUT}/gcgame_{theme}_{wd}.png")
            sw = pg.evaluate("document.documentElement.scrollWidth")
            if sw > wd: errs.append(f"{theme}{wd}: horizontal overflow {sw}")
            pg.close()
    b.close()
print("ERRORS:", errs)
